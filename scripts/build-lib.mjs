#!/usr/bin/env node
/**
 * build-lib.mjs — 从 src/client.js 生成浏览器产物 lib/client.js。
 *
 * src/client.js 是 Module Loader 脚本（顶层调用
 * `window.__ModuleLoader__.load({ id, factory })`，无 ESM import/export），
 * 因此构建 = 校验 + 加生成头 + 复制 + 语法检查。
 * 客户端半经 package.json 的 dsh.client（platform: 'web'）与
 * exports["./client"] 对外暴露。
 */
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const src = join(root, 'src', 'client.js')
const outDir = join(root, 'lib')
const out = join(outDir, 'client.js')

const source = await readFile(src, 'utf8')

// 校验 1：不得使用 ESM import/export —— 客户端以 classic script 执行。
if (/(^|\n)\s*(import|export)\s/.test(source)) {
  console.error('[build-lib] src/client.js must be a classic script (no import/export); use window.__ModuleLoader__.load')
  process.exit(1)
}
if (/from\s+['"]node:/.test(source) || /\brequire\(\s*['"]node:/.test(source)) {
  console.error('[build-lib] src/client.js references node builtins')
  process.exit(1)
}
// 校验 2：必须注册 Module Loader factory，且 id 与包名一致。
if (!/window\.__ModuleLoader__\.load\(\s*\{/.test(source)) {
  console.error('[build-lib] src/client.js must call window.__ModuleLoader__.load({ ... })')
  process.exit(1)
}
if (!/id:\s*['"]dsh-archived-session-cleaner['"]/.test(source)) {
  console.error('[build-lib] src/client.js must register id "dsh-archived-session-cleaner"')
  process.exit(1)
}
if (!/factory\s*\(?\s*require\s*\)?/.test(source)) {
  console.error('[build-lib] src/client.js must declare factory(require)')
  process.exit(1)
}

const banner = `/* Generated by scripts/build-lib.mjs — do not edit.
 * Source: src/client.js (dsh-archived-session-cleaner)
 * Built: ${new Date().toISOString()}
 */
`
await mkdir(outDir, { recursive: true })
await writeFile(out, banner + source, 'utf8')

// 校验 3：生成物可被 JS 引擎解析（不执行）。
execFileSync(process.execPath, ['--check', out], { stdio: 'inherit' })
console.log(`[build-lib] wrote ${out} (${source.length} bytes source)`)
